/**
 * Canonical serialisation and hashing.
 *
 * Every resolved turn stores `sha256(canonicalJson(before, orders, seed, turn,
 * ruleVersion, after))`. CI re-simulates committed golden games and diffs those
 * hashes, which is how accidental rules drift gets caught before it silently
 * invalidates stored replays.
 *
 * SHA-256 is implemented here rather than imported because the engine must run
 * unchanged in the browser and must not reach for Node built-ins.
 */

/**
 * JSON with object keys sorted recursively, so two structurally equal values
 * always serialise to identical bytes regardless of construction order.
 */
export function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== 'object') {
    return JSON.stringify(value) ?? 'null';
  }
  if (Array.isArray(value)) {
    return `[${value.map(canonicalJson).join(',')}]`;
  }
  const record = value as Record<string, unknown>;
  const keys = Object.keys(record).sort();
  const parts = keys
    .filter((key) => record[key] !== undefined)
    .map((key) => `${JSON.stringify(key)}:${canonicalJson(record[key])}`);
  return `{${parts.join(',')}}`;
}

